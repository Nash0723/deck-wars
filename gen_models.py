# Builds src/shared/CreatureModelData.luau from the model files and checks it against the card list.
import sys, glob, msgpack
from cards import C
from modelkit import to_luau
import models_snack, models_junk, models_weather, models_critter, models_spooky, models_robo, models_extra

FILES = [models_snack, models_junk, models_weather, models_critter, models_spooky, models_robo, models_extra]
models = [fn() for mod in FILES for fn in mod.MODELS]
ids = [m.id for m in models]
dupes = {i for i in ids if ids.count(i) > 1}
assert not dupes, f"duplicate model ids: {dupes}"

need = [c[0] for c in C if c[2] in ("Creature", "Building")] + ["ghost", "pigeon", "hero_bonk", "hero_granny_bolt", "bot_bonkers"]
missing = [i for i in need if i not in ids]
extra = [i for i in ids if i not in need]
assert not missing, f"models missing for: {missing}"
assert not extra, f"models without a card: {extra}"

# Validate materials against the Roblox reflection database
import os
# Roblox's API list comes with Rojo's crates (run `cargo install rojo --locked` once)
_cargo = os.environ.get('CARGO_HOME', os.path.expanduser('~/.cargo'))
_found = sorted(glob.glob(os.path.join(_cargo, 'registry', 'src', '*', 'rbx_reflection_database-*', 'database.msgpack')))
if not _found: sys.exit('Roblox API list not found: run `cargo install rojo --locked` first')
p = _found[-1]
db = msgpack.unpackb(open(p, 'rb').read(), raw=False, strict_map_key=False)
enums = db[2]
material_names = set(enums["Material"][1].keys()) if isinstance(enums["Material"], list) else set(enums["Material"]["items"].keys())
problems = []
for m in models:
    for part in m.parts:
        if part["mat"] not in material_names:
            problems.append(f"{m.id}: unknown material {part['mat']}")
        if min(part["size"]) < 0.02:
            problems.append(f"{m.id}: part {part['name']} is very thin {part['size']}")
    lo, hi = m.bounds()
    w, d = hi[0] - lo[0], hi[2] - lo[2]
    limit = {"creature": 5.3, "token": 4.6, "gadget": 3.8, "hero": 3.2, "avatar": 6.0, "terrain": 4.6}[m.kind]
    if max(w, d) > limit + 0.01:
        problems.append(f"{m.id}: footprint {w:.2f} x {d:.2f} is bigger than {limit}")
for pr in problems:
    print("WARN", pr)

header = ("-- Generated by gen_models.py from the models_*.py files. Do not edit by hand.\n"
          "-- Each part: { shape, name, sizeX, sizeY, sizeZ, posX, posY, posZ, rotX, rotY, rotZ (degrees), R, G, B, material, transparency, reflectance }\n"
          "-- shape: B block, S ball, C cylinder, E ellipsoid (block with a sphere mesh), W wedge.\n"
          "-- Models stand on y = 0 and face -Z. CreatureBuilder turns this data into Roblox models.")
src = to_luau(models, header)
open("src/shared/CreatureModelData.luau", "w").write(src)
total = sum(len(m.parts) for m in models)
print(f"{len(models)} models, {total} parts, {len(src) // 1024} KB")
